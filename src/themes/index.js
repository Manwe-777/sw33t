// Get list of all theme IDs
export const themeIds = Object.keys(themes);

// Get theme by ID
export function getTheme(id) {
  return themes[id] || themes.monokai;
}

// Apply theme to document
export function applyTheme(themeId, mode = "dark") {
  const theme = getTheme(themeId);
  const colors = theme[mode] || theme.dark;
  const root = document.documentElement;

  root.style.setProperty("--bg-primary", colors.bgPrimary);
  root.style.setProperty("--bg-secondary", colors.bgSecondary);
  root.style.setProperty("--bg-tertiary", colors.bgTertiary);
  root.style.setProperty("--bg-elevated", colors.bgElevated);
  root.style.setProperty("--bg-hover", colors.bgHover);
  root.style.setProperty("--bg-input", colors.bgInput);
  root.style.setProperty("--text-primary", colors.textPrimary);
  root.style.setProperty("--text-secondary", colors.textSecondary);
  root.style.setProperty("--text-muted", colors.textMuted);
  root.style.setProperty("--border-color", colors.borderColor);
  root.style.setProperty("--border-subtle", colors.borderSubtle);
  root.style.setProperty("--accent", colors.accent);
  root.style.setProperty("--accent-hover", colors.accentHover);
  root.style.setProperty("--accent-subtle", colors.accentSubtle);
  root.style.setProperty("--success", colors.success);
  root.style.setProperty("--success-subtle", colors.successSubtle);
  root.style.setProperty("--danger", colors.danger);
  root.style.setProperty("--danger-subtle", colors.dangerSubtle);
  root.style.setProperty("--warning", colors.warning);

  // Store current theme info
  root.setAttribute("data-theme", mode);
  root.setAttribute("data-theme-id", themeId);
}
